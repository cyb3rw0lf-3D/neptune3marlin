import { pick } from '../../core/random';
import type { VehicleSpec } from '../../vehicles/specs';
import { HAND, type LessonDef, type MistakeDef, type StepDef } from '../engine/types';
import { liftSteps, lowerStep, ppeStep } from './common';

export interface EvCoolantVariant {
  /** The vacuum test finds a loose hose clamp. */
  leak: boolean;
  /** What the old coolant looks like. */
  old: 'ok' | 'murky';
}

const NOT_ISOLATED: MistakeDef = {
  code: 'evcool.hv.not_isolated',
  kind: 'safety',
  label: 'Opened the battery cooling loop before isolating the high-voltage system',
  explain:
    'The battery coolant runs right through the high-voltage pack. Before you open that loop, the car is switched off, the fob is locked away, the 12-volt battery is disconnected, and the service disconnect is pulled and locked out. Then the capacitors get their full wait.',
  consequence: 'spark',
};

const WRONG_COOLANT: MistakeDef = {
  code: 'evcool.fill.wrong_type',
  kind: 'wrong-item',
  label: 'Grabbed ordinary engine coolant for a battery cooling loop',
  explain:
    'Battery cooling loops need the maker’s low-conductivity coolant. Ordinary coolant, and above all tap water, conducts electricity. A leak inside the pack can then cause an isolation fault or a short. Only the approved EV coolant goes in.',
};

const NO_VACUUM_TEST: MistakeDef = {
  code: 'evcool.vacuum.skipped',
  kind: 'procedure',
  label: 'Filled the loop without a vacuum leak test',
  explain:
    'The vacuum fill tool does two jobs: it proves the loop holds a vacuum, so it has no leaks, and it fills the loop with no air pockets. Skip the hold test and a leak inside the pack can go unnoticed.',
};

const NO_BLEED: MistakeDef = {
  code: 'evcool.bleed.skipped',
  kind: 'procedure',
  label: 'Finished without running the coolant bleed routine',
  explain:
    'Battery loops have pumps and valves that trap air. The scan tool’s coolant bleed routine runs the pumps and switches the valves to push every bubble out. Air left in the loop lets cells overheat.',
  consequence: 'buzz',
};

export const evCoolant: LessonDef<EvCoolantVariant> = {
  id: 'ev-coolant',
  title: 'EV Battery Coolant Service',
  summary: 'Isolate high voltage, drain, vacuum-test and fill the battery loop, then run the bleed routine.',
  available: true,
  vehicles: ['ev'],
  cartItems: [
    'coolant-ev',
    'coolant-green',
    'vacuum-fill',
    'ratchet-10',
    'loto-tag',
    'key-fob',
    'drain-pan',
    'scan-tool',
  ],
  intro:
    'An EV’s battery pack has its own cooling loop. Coolant there keeps the cells at a safe temperature, and it runs right past high-voltage parts. Today you make the car safe, change the coolant, prove the loop has no leaks, and bleed every bubble out.',
  outro:
    'High voltage isolated and restored by the book, the right coolant, a leak-tested loop and no air in it. Battery packs are the most expensive part of an EV, and you just protected one.',
  variant: (rng) => ({
    leak: rng() < 0.5,
    old: pick(rng, ['ok', 'ok', 'murky'] as const),
  }),
  workOrder: (vehicle) => [
    `${vehicle.name}: battery coolant service due, coolant warning light`,
    'Coolant: maker-approved low-conductivity EV coolant ONLY',
    `Isolate HV first. Wait after disconnect: ${vehicle.hv?.waitMinutes ?? 10} min`,
    'Vacuum test: must hold 25 inHg for 1 minute',
  ],
  stage: () => ({
    evKit: true,
    drainPan: true,
    scan: {
      live: [
        'Service: battery coolant bleed',
        'Pumps cycling, valves switching',
        'Air purge: 100% complete',
        'Coolant temp: 68 °F',
        'Routine finished. Check the level.',
      ],
    },
    scanLabels: { 'scan-live': 'Coolant bleed' },
  }),
  steps: (vehicle, v) => steps(vehicle, v),
};

function steps(vehicle: VehicleSpec, v: EvCoolantVariant): StepDef[] {
  const wait = vehicle.hv?.waitMinutes ?? 10;
  const out: StepDef[] = [
    ppeStep('Coolant splashes, and you will work near high-voltage parts. Glasses and gloves on.'),
    {
      id: 'spec',
      label: 'Look up the coolant spec',
      say: 'Open the service information. Which coolant goes in this battery loop?',
      hint: 'Battery loops are fussy about coolant.',
      item: HAND,
      targets: [],
      gesture: { kind: 'press' },
      choice: {
        prompt: 'What may go into the battery cooling loop?',
        options: [
          'Only the maker-approved low-conductivity EV coolant',
          'Any coolant that matches the color',
          'Tap water is fine to top it up',
        ],
        correct: 0,
        wrong: WRONG_COOLANT,
        right: 'Right. The teal jug is the approved EV coolant.',
      },
    },
    {
      id: 'power-off',
      label: 'Switch the car off',
      say: 'Press the power button to switch the car off.',
      hint: 'The power button is on the dash.',
      spot: 'driver',
      item: HAND,
      targets: ['start-button'],
      gesture: { kind: 'press' },
      effects: [{ fx: 'engine-off' }],
    },
    {
      id: 'fob',
      label: 'Lock the key fob away from the car',
      say: 'Lock the key fob in the lockbox on the battery bench, so the car cannot wake itself up.',
      hint: 'The lockbox is on the battery bench.',
      spot: 'bench',
      item: 'key-fob',
      targets: ['lockbox'],
      gesture: { kind: 'press' },
      effects: [{ fx: 'fob-lockbox' }],
      safety: true,
    },
    {
      id: 'hood',
      label: 'Open the frunk',
      say: 'Open the frunk. The battery coolant reservoir and the 12-volt battery are inside.',
      hint: 'The frunk latch is at the front.',
      spot: 'hood',
      item: HAND,
      targets: ['hood-latch'],
      gesture: { kind: 'press' },
      effects: [{ fx: 'hood-open' }],
    },
    {
      id: '12v-off',
      label: 'Disconnect the 12-volt negative cable',
      say: 'Disconnect the negative cable on the 12-volt battery. Without 12 volts, the high-voltage contactors cannot close.',
      hint: 'Negative first, as always.',
      spot: 'hood',
      item: 'ratchet-10',
      targets: ['batt-neg'],
      gesture: { kind: 'twist', turns: 1, dir: 'ccw' },
      requires: ['fob'],
      effects: [{ fx: 'cable-off' }],
      safety: true,
    },
    {
      id: 'disconnect',
      label: 'Pull the service disconnect',
      say: 'Pull the orange service disconnect straight out. It splits the battery pack in two inside.',
      hint: 'The orange handle in the frunk.',
      spot: 'hood',
      item: HAND,
      targets: ['service-disconnect'],
      gesture: { kind: 'hold', seconds: 1.2 },
      requires: ['12v-off'],
      effects: [{ fx: 'sd-out' }],
      safety: true,
    },
    {
      id: 'lockout',
      label: 'Lock out and tag the disconnect',
      say: 'Put the lockout tag on the empty socket, so nobody can put the disconnect back while the loop is open.',
      hint: 'The red tag on the cart.',
      spot: 'hood',
      item: 'loto-tag',
      targets: ['service-disconnect'],
      gesture: { kind: 'press' },
      effects: [{ fx: 'loto' }],
      safety: true,
    },
    {
      id: 'wait',
      label: `Wait ${wait} minutes`,
      say: `Start the wait timer. The capacitors need ${wait} minutes to discharge. I will fast-forward it for you.`,
      hint: 'There is a timer on the safety kit table.',
      spot: 'ev-kit',
      item: HAND,
      targets: ['wait-timer'],
      gesture: { kind: 'press' },
      skipMistake: NOT_ISOLATED,
      effects: [{ fx: 'wait' }],
      safety: true,
    },
    ...liftSteps(),
    {
      id: 'pan',
      label: 'Place the drain pan under the coolant drain',
      say: 'Set the drain pan on the floor under the battery coolant drain.',
      hint: 'Something has to catch the coolant first.',
      spot: 'under',
      item: 'drain-pan',
      targets: ['pan-spot'],
      gesture: { kind: 'press' },
      requires: ['lock', 'wait'],
      effects: [{ fx: 'pan-place' }],
    },
    {
      id: 'drain',
      label: 'Open the battery coolant drain',
      say: 'Open the yellow drain plug at the front of the battery pack and let the old coolant drain into the pan.',
      hint: 'The drain is at the front edge of the pack.',
      spot: 'under',
      item: HAND,
      targets: ['ev-coolant-drain'],
      gesture: { kind: 'twist', turns: 1, dir: 'ccw' },
      requires: ['wait', 'pan'],
      readings: {
        'ev-coolant-drain': {
          text: v.old === 'murky' ? 'Old coolant: murky, with flecks' : 'Old coolant: clear, just old',
        },
      },
      effects: [{ fx: 'inspect' }],
    },
    {
      id: 'drain-close',
      label: 'Close the drain',
      say: 'When it stops dripping, refit the drain plug and snug it down.',
      hint: 'Clockwise to close.',
      spot: 'under',
      item: HAND,
      targets: ['ev-coolant-drain'],
      gesture: { kind: 'twist', turns: 1, dir: 'cw' },
      effects: [{ fx: 'inspect' }],
    },
    lowerStep(['drain-close']),
    {
      id: 'vac-on',
      label: 'Fit the vacuum fill tool on the reservoir',
      say: 'Seal the vacuum fill tool onto the battery coolant reservoir.',
      hint: 'It replaces the reservoir cap.',
      spot: 'hood',
      item: 'vacuum-fill',
      targets: ['coolant-reservoir'],
      gesture: { kind: 'press' },
      requires: ['lower'],
      fit: true,
      effects: [{ fx: 'inspect' }],
    },
    {
      id: 'vac-hold',
      label: 'Pull a vacuum and watch the gauge',
      say: 'Pull the loop down to 25 inches of vacuum, close the valve, and watch the gauge for a full minute.',
      hint: 'A steady needle means no leaks.',
      spot: 'hood',
      item: HAND,
      targets: ['coolant-reservoir'],
      gesture: { kind: 'hold', seconds: 2.5 },
      skipMistake: NO_VACUUM_TEST,
      readings: {
        'coolant-reservoir': {
          text: v.leak ? 'The needle drops from 25 to 15 inHg: a leak' : 'Holds steady at 25 inHg for a minute',
        },
      },
      effects: [{ fx: 'inspect' }],
    },
  ];
  if (v.leak) {
    out.push(
      {
        id: 'leak-call',
        label: 'Decide what the dropping gauge means',
        say: 'The vacuum did not hold. What now?',
        hint: 'Never fill a loop that leaks.',
        item: HAND,
        targets: [],
        gesture: { kind: 'press' },
        choice: {
          prompt: 'The gauge dropped from 25 to 15 inHg. What do you do?',
          options: [
            'Find and fix the leak, then test again before filling',
            'Fill it anyway; the coolant will seal it',
            'Top it up more often',
          ],
          correct: 0,
          wrong: {
            code: 'evcool.vacuum.leak_ignored',
            kind: 'procedure',
            label: 'Filled a cooling loop that failed the vacuum test',
            explain:
              'A loop that will not hold vacuum leaks. Coolant would drip out there, and if the leak is near the pack, onto high-voltage parts. Find it and fix it, then prove it with another vacuum test.',
          },
        },
      },
      {
        id: 'clamp',
        label: 'Tighten the loose hose clamp',
        say: 'Check the hoses from the reservoir. One clamp is loose: tighten it.',
        hint: 'Look at the hose under the reservoir.',
        spot: 'hood',
        item: HAND,
        targets: ['ev-hose-clamp'],
        gesture: { kind: 'twist', turns: 1, dir: 'cw' },
        effects: [{ fx: 'inspect' }],
      },
      {
        id: 'vac-retest',
        label: 'Test the vacuum again',
        say: 'Pull the vacuum down again and watch the gauge for a minute.',
        hint: 'This time it should hold.',
        spot: 'hood',
        item: HAND,
        targets: ['coolant-reservoir'],
        gesture: { kind: 'hold', seconds: 2.5 },
        readings: { 'coolant-reservoir': { text: 'Holds steady at 25 inHg for a minute' } },
        effects: [{ fx: 'inspect' }],
      },
    );
  }
  out.push(
    {
      id: 'fill',
      label: 'Fill the loop with the approved EV coolant',
      say: 'Put the tool’s pickup hose in the approved EV coolant and open the valve. The vacuum draws the coolant in with no air.',
      hint: 'The teal jug is the approved EV coolant.',
      spot: 'hood',
      item: 'coolant-ev',
      targets: ['coolant-reservoir'],
      gesture: { kind: 'hold', seconds: 2.5 },
      requires: [v.leak ? 'vac-retest' : 'vac-hold'],
      wrongItems: { 'coolant-green': WRONG_COOLANT },
      effects: [{ fx: 'oil-fill' }],
    },
    {
      id: 'vac-off',
      label: 'Take the vacuum fill tool off',
      say: 'Take the vacuum fill tool off the reservoir and refit the cap.',
      hint: 'The loop is full.',
      spot: 'hood',
      item: HAND,
      targets: ['coolant-reservoir'],
      gesture: { kind: 'press' },
      skipMistake: {
        code: 'evcool.vacuum_tool.left_on',
        kind: 'order',
        label: 'Tried to finish with the vacuum fill tool still on the car',
        explain:
          'Take the vacuum fill tool off first. A tool left on a car goes home with the customer, or falls off on the road. Everything you fit to the car comes off again before you call the job done.',
      },
      unfit: ['vacuum-fill'],
      effects: [{ fx: 'inspect' }],
    },
    {
      id: 'unlock',
      label: 'Remove the lockout tag and refit the disconnect',
      say: 'The loop is closed. Take your lockout tag off and push the service disconnect firmly back in.',
      hint: 'Only the person who locked it out takes the tag off.',
      spot: 'hood',
      item: HAND,
      targets: ['service-disconnect'],
      gesture: { kind: 'hold', seconds: 1.2 },
      requires: ['vac-off'],
      stepEffects: [{ fx: 'loto-off' }, { fx: 'sd-in' }],
    },
    {
      id: '12v-on',
      label: 'Reconnect the 12-volt negative cable',
      say: 'Reconnect the 12-volt negative cable and tighten it.',
      hint: 'Negative goes back on last.',
      spot: 'hood',
      item: 'ratchet-10',
      targets: ['batt-neg'],
      gesture: { kind: 'twist', turns: 1, dir: 'cw' },
      effects: [{ fx: 'cable-on' }],
    },
    {
      id: 'fob-back',
      label: 'Get the key fob from the lockbox',
      say: 'Take the key fob back out of the lockbox.',
      hint: 'The lockbox is on the battery bench.',
      spot: 'bench',
      item: HAND,
      targets: ['lockbox'],
      gesture: { kind: 'press' },
      effects: [{ fx: 'inspect' }],
    },
    {
      id: 'power-on',
      label: 'Switch the car on',
      say: 'Switch the car on so the scan tool can run the coolant pumps.',
      hint: 'The power button is on the dash.',
      spot: 'driver',
      item: HAND,
      targets: ['start-button'],
      gesture: { kind: 'press' },
      effects: [{ fx: 'engine-run' }],
    },
    {
      id: 'scan',
      label: 'Plug the scan tool into the OBD-II port',
      say: 'Take the scan tool from its hook on the lift post and plug it into the OBD-II port under the dash.',
      hint: 'The port is under the dash on the driver side.',
      spot: 'driver',
      item: 'scan-tool',
      targets: ['dlc'],
      gesture: { kind: 'press' },
      effects: [{ fx: 'scan-plug' }],
    },
    {
      id: 'bleed',
      label: 'Run the coolant bleed routine',
      say: 'Press Coolant bleed on the scan tool. It runs the pumps and switches the valves to push the air out of the loop.',
      hint: 'The Coolant bleed button on the scan tool.',
      spot: 'driver',
      item: HAND,
      targets: ['scan-live'],
      gesture: { kind: 'press' },
      skipMistake: NO_BLEED,
      readings: { 'scan-live': { text: 'Coolant bleed: air purge 100% complete' } },
      effects: [{ fx: 'inspect' }],
    },
    {
      id: 'level',
      label: 'Check the level after the routine',
      say: 'The bleed routine pushed the air out, so the level dropped. Top it to the MAX line with the approved coolant.',
      hint: 'The reservoir in the frunk.',
      spot: 'hood',
      item: 'coolant-ev',
      targets: ['coolant-reservoir'],
      gesture: { kind: 'hold', seconds: 1.5 },
      requires: ['bleed'],
      wrongItems: { 'coolant-green': WRONG_COOLANT },
      readings: { 'coolant-reservoir': { text: 'At the MAX line' } },
      effects: [{ fx: 'oil-fill' }],
    },
    {
      id: 'leaks',
      label: 'Check the floor for leaks',
      say: 'Look under the front of the car. There must be no drips.',
      hint: 'Check the floor under the frunk and the pack.',
      spot: 'hood',
      item: HAND,
      targets: ['leak-check'],
      gesture: { kind: 'press' },
      readings: { 'leak-check': { text: 'Dry floor, no drips' } },
      effects: [{ fx: 'inspect' }],
    },
    {
      id: 'recycle',
      label: 'Pour the old coolant into the recycling drum',
      say: 'Carry the drain pan to the recycling drum and pour the old coolant in.',
      hint: 'The old coolant is still in the drain pan.',
      spot: 'recycle',
      item: 'drain-pan',
      targets: ['recycle-drum'],
      gesture: { kind: 'hold', seconds: 2 },
      effects: [{ fx: 'oil-recycle' }],
    },
    {
      id: 'close',
      label: 'Close the frunk',
      say: 'Lower the frunk lid and latch it.',
      hint: 'Leave the car the way it came in.',
      spot: 'hood',
      item: HAND,
      targets: ['hood-latch'],
      gesture: { kind: 'press' },
      effects: [{ fx: 'hood-close' }],
    },
  );
  return out;
}
